"""Generate src/recognition_hierarchy.hpp: which app categories are parents of which, from Open Images.

Open Images nests its classes (a dog is also a carnivore, a mammal and an animal; a taxi is also a car), and its
detectors may report both a child and its parent on one object. The app uses this table to hide a parent box that
duplicates a child box. Inputs are the app vocabulary (dependencies/recognition-vocabulary.json) and the Open
Images class hierarchy and class names, downloaded into --cache unless already there.

Usage: python scripts/generate-hierarchy.py [--cache data/openimages-metadata]
"""
from __future__ import annotations

import argparse
import csv
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HIERARCHY = 'https://storage.googleapis.com/openimages/2018_04/bbox_labels_600_hierarchy.json'
NAMES = 'https://storage.googleapis.com/openimages/v7/oidv7-class-descriptions-boxable.csv'
# The app's Open Images labels come from the YOLOv8 Open Images model; nine were renamed in V7.
RENAMED = {'Airplane': 'Fixed-wing aircraft', 'Ball': 'Ball (Object)', 'Coffee': 'Coffee (drink)',
           'Earrings': 'Earring', 'Egg (Food)': 'Egg', 'Human beard': 'Beard', 'Lemon': 'Lemon (plant)',
           'Maracas': 'Maraca', 'Orange': 'Orange (fruit)'}


def fetch(url: str, cache: Path) -> Path:
    target = cache / url.rsplit('/', 1)[1]
    if not target.exists():
        cache.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url, timeout=120) as response:
            target.write_bytes(response.read())
    return target


def ancestor_pairs(vocabulary: dict, hierarchy: dict, mid_by_name: dict[str, str]) -> list[tuple[int, int]]:
    """Sorted (category, ancestor category) pairs over app category IDs, without self pairs."""
    app_by_mid = {}
    for label, app_id in zip(vocabulary['openimages_labels'], vocabulary['openimages_ids']):
        app_by_mid[mid_by_name[RENAMED.get(label, label)]] = app_id
    parents: dict[str, set[str]] = {}

    def walk(node: dict) -> None:
        for child in node.get('Subcategory', ()):
            parents.setdefault(child['LabelName'], set()).add(node['LabelName'])
            walk(child)
    walk(hierarchy)
    pairs = set()
    for mid, app_id in app_by_mid.items():
        stack, seen = [mid], set()
        while stack:
            for parent in parents.get(stack.pop(), ()):
                if parent not in seen:
                    seen.add(parent)
                    stack.append(parent)
        pairs |= {(app_id, app_by_mid[m]) for m in seen if m in app_by_mid and app_by_mid[m] != app_id}
    return sorted(pairs)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cache', type=Path, default=ROOT / 'data' / 'openimages-metadata')
    parser.add_argument('--out', type=Path, default=ROOT / 'src' / 'recognition_hierarchy.hpp')
    args = parser.parse_args()
    vocabulary = json.loads((ROOT / 'dependencies' / 'recognition-vocabulary.json').read_text(encoding='utf-8'))
    hierarchy = json.loads(fetch(HIERARCHY, args.cache).read_text(encoding='utf-8'))
    with fetch(NAMES, args.cache).open(encoding='utf-8') as handle:
        mid_by_name = {row[1]: row[0] for row in csv.reader(handle) if row and row[0] != 'LabelName'}
    pairs = ancestor_pairs(vocabulary, hierarchy, mid_by_name)
    names = vocabulary['classes']
    lines = [
        '#pragma once',
        '// Generated by scripts/generate-hierarchy.py from the Open Images class hierarchy; do not edit.',
        '#include <array>',
        '#include <utility>',
        'namespace frametrail::vocabulary {',
        '// Sorted (category, ancestor) pairs of app category IDs: a dog is also an animal, a taxi also a car.',
        f'inline constexpr std::array<std::pair<short,short>,{len(pairs)}> ancestors={{{{',
    ]
    lines += [f'    {{{child},{parent}}}, // {names[child]} < {names[parent]}' for child, parent in pairs]
    lines += ['}};', '}', '']
    args.out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{args.out}: {len(pairs)} pairs over {len({c for c, _ in pairs})} categories')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
