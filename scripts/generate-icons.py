"""Generate apps/desktop/fluent_icons.hpp from Microsoft's Fluent UI System Icons (MIT).

The desktop app draws icons as filled vector paths (QPainterPath), so it needs no SVG module or
image assets and every icon stays sharp and can be tinted. This script turns the 20 px "regular"
SVGs into plain M/L/Q/C/Z path data (arcs become cubic curves).

Usage (needs `pip install svgelements`; the icons come from the npm package @fluentui/svg-icons):
    npm pack @fluentui/svg-icons && tar xzf fluentui-svg-icons-*.tgz
    python scripts/generate-icons.py --package package --out apps/desktop/fluent_icons.hpp
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

# App name -> Fluent icon (20 px regular unless the name ends in _filled).
ICONS = {
    'home': 'home', 'preview': 'video_clip', 'analysis': 'data_bar_vertical', 'playback': 'movies_and_tv',
    'camera': 'camera', 'camera_off': 'camera_off', 'guide': 'question_circle', 'settings': 'settings',
    'open': 'folder_open', 'play': 'play_filled', 'pause': 'pause_filled', 'stop': 'stop_filled',
    'replay': 'arrow_counterclockwise', 'save': 'save', 'export': 'arrow_export_ltr', 'inspector': 'panel_right',
    'line': 'pen', 'dismiss': 'dismiss', 'sync': 'arrow_sync', 'search': 'search', 'check': 'checkmark',
    'chevron_down': 'chevron_down', 'chevron_up': 'chevron_up', 'local': 'shield_checkmark', 'info': 'info',
    'warning': 'warning', 'error': 'error_circle', 'brand': 'scan_object', 'video': 'video', 'clock': 'clock',
    'list': 'apps_list_detail', 'upload': 'arrow_upload', 'tag': 'tag', 'history': 'history',
}


def path_data(svg: str) -> str:
    from svgelements import Close, CubicBezier, Line, Move, Path as SvgPath, QuadraticBezier
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not paths:
        raise ValueError('no <path> in icon')
    out = []
    fmt = lambda p: f'{round(p.x, 3):g} {round(p.y, 3):g}'
    for d in paths:
        path = SvgPath(d)
        path.approximate_arcs_with_cubics()
        for segment in path:
            if isinstance(segment, Move):
                out.append('M' + fmt(segment.end))
            elif isinstance(segment, Close):
                out.append('Z')
            elif isinstance(segment, Line):
                out.append('L' + fmt(segment.end))
            elif isinstance(segment, QuadraticBezier):
                out.append('Q' + fmt(segment.control) + ' ' + fmt(segment.end))
            elif isinstance(segment, CubicBezier):
                out.append('C' + fmt(segment.control1) + ' ' + fmt(segment.control2) + ' ' + fmt(segment.end))
            else:
                raise ValueError(f'unsupported segment {type(segment).__name__}')
    return ''.join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--package', type=Path, required=True, help='unpacked @fluentui/svg-icons package folder')
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    version = json.loads((args.package / 'package.json').read_text(encoding='utf-8'))['version']
    lines = [
        '#pragma once',
        f'// Generated by scripts/generate-icons.py from @fluentui/svg-icons {version}',
        '// (Fluent UI System Icons, Copyright (c) 2020 Microsoft Corporation, MIT License). Do not edit.',
        '// 20 x 20 path data with absolute M/L/Q/C/Z commands; fill with Qt::WindingFill.',
        '#include <string_view>',
        '#include <utility>',
        '',
        'inline constexpr std::pair<std::string_view, std::string_view> fluent_icon_paths[] = {',
    ]
    for name, icon in ICONS.items():
        style = 'filled' if icon.endswith('_filled') else 'regular'
        stem = icon.removesuffix('_filled')
        svg = (args.package / 'icons' / f'{stem}_20_{style}.svg').read_text(encoding='utf-8')
        lines.append(f'    {{"{name}", "{path_data(svg)}"}},')
    lines += ['};', '']
    args.out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'Wrote {len(ICONS)} icons to {args.out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
